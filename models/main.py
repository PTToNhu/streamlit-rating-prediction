import os

import os

import pandas as pd
import numpy as np
import ast
import json
import re
from collections import Counter

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import OneHotEncoder
from category_encoders import TargetEncoder
from sklearn.decomposition import PCA
from sklearn.metrics import mean_squared_error, mean_absolute_error
import joblib

from sentence_transformers import SentenceTransformer

import matplotlib.pyplot as plt
import xgboost as xgb
from models.preprocessor import EcommercePreprocessor

# =========================
# LOAD DATA
# =========================
BASE_DIR = os.path.dirname(os.path.abspath(__file__))
data_path = os.path.join(BASE_DIR, "..", "dataset", "mart_product_info.xlsx")
df = pd.read_excel(data_path)

###########################################################
# TRAIN TEST SPLIT BEFORE PREPROCESSING
###########################################################

y = df['rating'].astype(float)
X_df = df.drop(columns=['rating'])

X_train_df, X_test_df, y_train, y_test = train_test_split(
    X_df,
    y,
    test_size=0.2,
    random_state=42
)
X_train_df.columns

###########################################################
# PREPROCESSING
###########################################################

preprocessor = EcommercePreprocessor()

preprocessor.fit(X_train_df, y_train)

X_train = preprocessor.transform(X_train_df)
X_test = preprocessor.transform(X_test_df)

###########################################################
# SAVE
###########################################################
joblib.dump(preprocessor, 'preprocessor.pkl')

###########################################################
# MODEL
###########################################################

model = xgb.XGBRegressor(
    n_estimators=300,
    learning_rate=0.05,
    max_depth=6,
    subsample=0.8,
    colsample_bytree=0.8,
    random_state=42
)

model.fit(X_train, y_train)

preds = model.predict(X_test)


###########################################################
# SAVE
###########################################################

joblib.dump(model, 'xgb_model.pkl')

load_model = joblib.load('xgb_model.pkl')
load_preprocessor = joblib.load('preprocessor.pkl')

preds_loaded = load_model.predict(
    load_preprocessor.transform(X_test_df)
)
rmse = np.sqrt(
    np.mean((preds_loaded - y_test) ** 2)
)
print(f'RMSE of loaded model: {rmse}')

mae = np.mean(np.abs(preds_loaded - y_test))
print(f'MAE of loaded model: {mae}')